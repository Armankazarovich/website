// Тексты-подсказки, которые быстрые шаблоны админки раньше вставляли прямо
// в сторис. Это инструкции для менеджера, а не текст для покупателя.
// Найдено 10.09.2026: две сторис на боевом сайте показывали покупателям
// «…если указать slug товара» и «Коротко объясните процесс и следующий шаг».
// Список один на модуль: по нему админка предупреждает менеджера, а сайт
// не показывает такие строки покупателю.
export const STORY_TEMPLATE_HINTS = [
  "Покажите материал, размер и качество",
  "Эта сторис будет первой на странице связанного товара, если указать slug товара.",
  "Коротко объясните процесс и следующий шаг",
  "Сторис можно привязать к услуге по slug, чтобы она открывалась первой на странице услуги.",
  "Одобренный отзыв можно показать в общем виджете",
  "После модерации видео-отзыв работает как доверительный контент для всего сайта.",
  "Короткое видео онлайн-продавца встречает посетителя и помогает быстрее выбрать. Прямой эфир подключается отдельным модулем.",
] as const;

const HINTS = new Set<string>(STORY_TEMPLATE_HINTS);

export function isStoryTemplateHint(value?: string | null) {
  const text = String(value ?? "").trim();
  return text.length > 0 && HINTS.has(text);
}

// Покупателю — только настоящий текст: заготовка превращается в «нет текста».
export function buyerStoryText(value?: string | null) {
  return isStoryTemplateHint(value) ? null : value ?? null;
}
